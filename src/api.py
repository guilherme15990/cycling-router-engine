"""Fachada do motor de roteamento ciclavel.

Ponto unico de importacao da API publica. Os modulos ficam na raiz de
``src/`` e tambem podem ser importados por nome curto (por exemplo,
``from search import search_profile``); esta fachada reune tudo quando se
prefere um unico ``import api``.

Mapa das camadas
----------------

* **Grafo ciclavel** (``graph.*``): modelo, superficie, restricoes,
  simplificacao, validacao e serializacao (JSON/GeoJSON).
* **OSM** (``osm.*``): leitura offline de ``.osm.pbf``, parsing e construcao
  do grafo ciclavel.
* **Elevacao** (``elevation``): provedores de altitude, cache e perfil
  amostrado ao longo do arco.
* **Snapping** (``snapping``): grafo temporario de consulta para origem e
  destino.
* **Fisica** (``physical.*``): travessia (tempo, energia, velocidade) e
  modelo energetico (energia eletrica em Wh e viabilidade de bateria).
* **Fisiologia** (``physiology.*``): contratos de escala de Borg, zonas
  cardiacas, parametros metabolicos e previsao fisiologica (nunca medicao).
* **ML** (``ml.*``): fronteira de inferencia que consome ``EffortFeatures`` e
  produz ``PhysiologicalPrediction``.
* **Busca e selecao** (``search.*``): A* multiobjetivo sobre a fronteira
  Pareto e a selecao por perfil (ranking, diversidade, explicacao e
  estimativa energetica). Inclui um **estimador aproximado** para a busca
  (equilibrio de velocidade) e o **relatorio de erro/custo** contra o
  simulador completo — sem presumir admissibilidade.
* **Avaliacao** (``evaluation.*``): avaliacao fisica **completa** de uma rota
  (simulador, nao o estimador) + ``EffortFeatures`` + previsao fisiologica +
  validacao de circulacao, com **classificacao explicita** que declara a
  ausencia de modelo fisiologico calibrado (nunca a inventa).
* **Inteligencia** (``intelligence.*``): Camada 04 (ADR-027) — observacoes
  reais, features de treino/servico, modelos base, **artefato de modelo local
  versionado** (registro + carregamento offline + compatibilidade), treino
  reproduzivel, avaliacao do modelo (temporal e por ciclista), preditor local
  calibrado e **classificacao predicao x preferencia**. Inclui ainda, pelo
  ADR-028, a **estimativa de intensidade** (RPE + faixas ``i1``..``i5``,
  computacional e **nao calibrada** — nunca zona cardiaca real). Tudo
  **offline**.
* **Operacao offline** (``offline``): guard de rede que **proibe** download em
  execucao; **fonte geografica local** em ``osm.pbf`` (``osm.read_osm_pbf``) e
  elevacao **Terrarium** local (``elevation.TerrariumElevation``), com preparo
  de tiles por ``elevation_tiles`` (etapa de rede, fora do caminho de execucao).

A fisica e sempre a mesma: o perfil **nao** altera o modelo fisico. Ele muda
apenas quais metricas entram na fronteira Pareto e como as rotas sao
ordenadas e selecionadas. A estimativa energetica (Wh) e um estagio posterior
a selecao.

Example:
    >>> from api import route_profile_for
    >>> route_profile_for("electric").id
    'electric'

Version:
    A versao publica esta em ``api.__version__`` (SemVer). Ver
    ``CHANGELOG.md`` para o historico e a politica de estabilidade.
"""

